const catalogs: Record<AppLanguage, AppCopyCatalog> = {
  en: english,
  hi: hindi,
  hinglish,
};

export const appCopyKeys = Object.freeze(Object.keys(english) as AppCopyKey[]);
export const appLanguageChangeEvent = "legal-saathi-language-change";
export const publicLanguageQueryParameter = "lang";

export function appCopy(language: AppLanguage, key: AppCopyKey) {
  return catalogs[language][key];
}

export function formatAppCopy(language: AppLanguage, key: AppCopyKey, values: Readonly<Record<string, string | number>>) {
  return appCopy(language, key).replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (placeholder, name: string) => {
    return Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder;
  });
}

export function documentLanguageFor(language: AppLanguage) {
  if (language === "hi") return "hi";
  if (language === "hinglish") return "hi-Latn";
  return "en";
}

export function appLanguageFromDocumentLanguage(value: string | null | undefined): AppLanguage {
  const normalized = value?.trim().toLowerCase();
  if (normalized === "hi") return "hi";
  if (normalized === "hi-latn") return "hinglish";
  return "en";
}

/**
 * Public policy pages can be opened directly, so their locale is encoded in a
 * small allowlisted URL parameter rather than relying on an authenticated
 * session or translating user-provided content.
 */
export function appLanguageFromSearch(search: string): AppLanguage | null {
  const parameter = new URLSearchParams(search.startsWith("?") ? search.slice(1) : search)
    .get(publicLanguageQueryParameter);
  return isAppLanguage(parameter) ? parameter : null;
}

/** Preserve any existing public query/hash state while carrying the UI locale. */
export function publicLanguageHref(path: string, language: AppLanguage) {
  const hashIndex = path.indexOf("#");
  const withoutHash = hashIndex === -1 ? path : path.slice(0, hashIndex);
  const hash = hashIndex === -1 ? "" : path.slice(hashIndex);
  const queryIndex = withoutHash.indexOf("?");
  const pathname = queryIndex === -1 ? withoutHash : withoutHash.slice(0, queryIndex);
  const search = queryIndex === -1 ? "" : withoutHash.slice(queryIndex + 1);
  const parameters = new URLSearchParams(search);
  parameters.set(publicLanguageQueryParameter, language);
  return `${pathname}?${parameters.toString()}${hash}`;
}

export function currentDocumentAppLanguage(): AppLanguage {
  if (typeof document === "undefined") return "en";
  const stored = document.documentElement.dataset.appLanguage;
  if (isAppLanguage(stored)) return stored;
  return appLanguageFromDocumentLanguage(document.documentElement.lang);
}

export function syncDocumentLanguage(language: AppLanguage) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = documentLanguageFor(language);
  document.documentElement.dataset.appLanguage = language;
  document.dispatchEvent(new CustomEvent<AppLanguage>(appLanguageChangeEvent, { detail: language }));
}
