const catalogs: Record<AppLanguage, AuthModalCatalog> = { en: english, hi: hindi, hinglish };

export const authModalCopyKeys = Object.keys(english) as AuthModalCopyKey[];

export function authModalCopy(language: AppLanguage, key: AuthModalCopyKey) {
  return catalogs[language][key];
}

export function formatAuthModalCopy(language: AppLanguage, key: "verificationCodeSentTo" | "recoveryCodeSentTo", values: { email: string }) {
  return authModalCopy(language, key).replace("{email}", values.email);
}
