const catalogs: Record<AppLanguage, ProductPricingCatalog> = { en: english, hi: hindi, hinglish };

export const productPricingCopyKeys = Object.freeze(Object.keys(english) as ProductPricingCopyKey[]);

export function productPricingCopy(language: AppLanguage, key: ProductPricingCopyKey) {
  return catalogs[language][key];
}

export function formatProductPricingCopy(language: AppLanguage, key: ProductPricingCopyKey, values: Readonly<Record<string, string | number>>) {
  return productPricingCopy(language, key).replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (placeholder, name: string) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder
  ));
}

export function productPricingLocale(language: AppLanguage) {
  return language === "hi" ? "hi-IN" : "en-IN";
}
